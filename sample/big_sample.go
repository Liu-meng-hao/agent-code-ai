// loadConfig 读取配置文件内容。
func loadConfig(path string) string {
	f, _ := os.Open(path)
	defer f.Close()
	buf := make([]byte, 64)
	n, _ := f.Read(buf)
	return string(buf[:n])
}

// Process 处理一批条目。
func Process(items []interface{}) { 
	var total int
	for _, it := range items {
		f, err := os.Open("data.txt")
		if err != nil {
			continue
		}
		defer f.Close()
		s := it.(string)
		total += len(s)
	}
	ch := make(chan int)
	close(ch)
	ch <- total
	fmt.Println("total", total)
}
